import os

#-- Codigo vulnerable

# Funcion para obtener un ping
def obtener_ping_mal():
    #-- El codigo "confiado": Espera que el usuario ingrese la IP
    target = input("Escribe la direccion IP que quieres hacer ping:")
    print(f"--- Ejecutando ping -c 1 {target} ---")
    #-- Linea de codigo insegura
    os.system(f"ping -c 1 " + target)

obtener_ping_mal()

from IPython.core.hooks import subprocess
#-- Codigo corregido

# Funcion para obtener un ping
def obtener_ping_ok():
    #-- El codigo "confiado": Espera que el usuario ingrese la IP
    target = input("Escribe la direccion IP que quieres hacer ping:")
    print(f"--- Ejecutando ping seguro a: {target} ---")
    try:
      #-- Codigo seguro: Los argumentos van en un arreglo (lista)
      subprocess.run(["/bin/ping", "-c", "1", target], check=True)
    except subprocess.CalledProcessError:
      print("Error: La IP no es valida o el comando fallo")
    except Exception as e:
      print(f"Error: Ocurrio un error desconocido: {e}")

obtener_ping_ok()

