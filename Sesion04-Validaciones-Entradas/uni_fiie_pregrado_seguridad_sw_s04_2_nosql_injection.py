#-- Ejm. La aplicacion NO verifica que user y pass sean cadenas.

def login_vulnerable(request):
  #-- ** Pintar la pantalla de log (consola)
  print("\n" + "=" * 70)
  print("UNI - FIEE - SESION 4 - LOGIN VULNERABLE")
  print("=" * 70)
  #-- ** Mostrar la consulta (se pasa el request, que viene de la capa de presentacion - ej. web o API)
  mostrar_consulta(request)
  #-- ** Arreglo de resultados (para almacenar los resultados, por defecto vacio)
  resultados = []
  #-- ** Supongamos que ya hemos traido aqui (o mejor dicho ya tuvimos acceso a la BD de users)
