print("--------- UNI-FIEE - Curso de Seguridad de Software - Sesion 03 --------------")

print("EJEMPLO DE CIFRADO SIMETRICO (DEBIL)")

# 1. Vamos a utilizar un cifrado debil (AES en modo ECB : Electronic Codebook), significa que
#    ECB cifra bloques iguales con el mismo resultado, la debilidad se manifiesta porque con ello
#    se revelan patrones que podrian revelar el algoritmo.

# --- Clave generada de forma aleatoria (ejm)
clave_128_bits = os.urandom(16)
data_repetitiva_1 = b"MENSAJE_SECRETO_MENSAJE_SECRETO_"  #--- 32 bytes

# ---- Cifrar el mensaje con AES en modo ECB
cifrador_ecb_1 = Cipher(algorithms.AES(clave_128_bits), modes.ECB())
encriptador_ecb_1 = cifrador_ecb_1.encryptor()
mensaje_cifrado_ecb_1 = encriptador_ecb_1.update(data_repetitiva_1) + encriptador_ecb_1.finalize()

#print("Mensaje cifrado con AES en modo ECB: ", mensaje_cifrado_ecb_1)
print("\n1. Cifrado debil (AES-ECB):")
print(f"Texto plano: {data_repetitiva_1}")
print(f"Texto cifrado: {mensaje_cifrado_ecb_1}")
print(f"Texto cifrado (en hexadecimal): {mensaje_cifrado_ecb_1.hex()}")

print(f"Texto cifrado (en hexadecimal) - Bloque 1: {mensaje_cifrado_ecb_1[:16].hex()}")
print(f"Texto cifrado (en hexadecimal) - Bloque 2: {mensaje_cifrado_ecb_1[16:].hex()}")

